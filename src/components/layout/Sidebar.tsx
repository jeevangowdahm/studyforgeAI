export function Sidebar() {
  const pathname = usePathname();
  const { sidebarCollapsed, setSidebarCollapsed } = useApp();
  const [theme, setThemeState] = React.useState<'dark' | 'light'>('dark');
  const setTheme = (value: 'dark' | 'light') => {
    setThemeState(value);
    document.documentElement.classList.toggle('dark', value === 'dark');
    localStorage.setItem('studyforge_theme', value);
  };

  return (
    <aside
      className={cn(
        'fixed left-0 top-0 z-40 h-screen transition-all duration-300 glass-strong neon-border',
        sidebarCollapsed ? 'w-16' : 'w-72'
      )}
      style={{ borderRight: '1px solid var(--border)' }}
    >
      <div className="flex flex-col h-full">
        {/* Logo */}
        <div className={cn('flex items-center gap-3 p-4 border-b border-border', sidebarCollapsed && 'justify-center')}>
          <div className="flex items-center justify-center w-10 h-10 rounded-xl bg-gradient-to-br from-cyan-500 to-purple-600">
            <svg className="w-6 h-6 text-white" fill="currentColor" viewBox="0 0 24 24">
              <path d="M12 2L2 7l10 5 10-5-10-5zM2 17l10 5 10-5M2 12l10 5 10-5" />
            </svg>
          </div>
          {!sidebarCollapsed && (
            <span className="font-bold text-xl text-gradient">StudyForge AI</span>
          )}
        </div>

        {/* Navigation */}
        <nav className="flex-1 p-3 space-y-1 overflow-y-auto" role="navigation" aria-label="Main navigation">
          {NAV_ITEMS.map((item) => {
            const isActive = pathname === item.href || (item.href !== '/dashboard' && pathname.startsWith(item.href));
            const Icon = iconMap[item.icon] || iconMap.LayoutDashboard;
            
            return (
              <Link
                key={item.href}
                href={item.href}
                className={cn(
                  'flex items-center gap-3 px-3 py-2.5 rounded-xl transition-all duration-200',
                  'relative overflow-hidden',
                  isActive
                    ? 'bg-gradient-to-r from-cyan-500/20 to-purple-500/20 text-cyan-400'
                    : 'text-slate-400 hover:text-white hover:bg-slate-800/50',
                  sidebarCollapsed && 'justify-center'
                )}
                title={sidebarCollapsed ? item.label : undefined}
                aria-current={isActive ? 'page' : undefined}
              >
                <span className="flex-shrink-0" aria-hidden="true">{Icon}</span>
                {!sidebarCollapsed && <span className="font-medium">{item.label}</span>}
                {isActive && !sidebarCollapsed && (
                  <span className="ml-auto w-1.5 h-1.5 rounded-full bg-cyan-400 animate-pulse" />
                )}
              </Link>
            );
          })}
        </nav>

        {/* Bottom section */}
        <div className={cn('p-3 border-t border-border', sidebarCollapsed && 'flex justify-center')}>
          {!sidebarCollapsed && (
            <div className="space-y-2">
              <button
                onClick={() => setTheme(theme === 'dark' ? 'light' : 'dark')}
                className="w-full flex items-center gap-3 px-3 py-2.5 rounded-xl text-slate-400 hover:text-white hover:bg-slate-800/50 transition-all"
              >
                <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                  <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d={theme === 'dark' ? "M12 3v1m0 16v1m9-9h-1M4 12H3m15.364 6.364l-.707-.707M6.343 6.343l-.707-.707m12.728 0l-.707.707M6.343 17.657l-.707.707M16 12a4 4 0 11-8 0 4 4 0 018 0z" : "M20.354 15.354A9 9 0 018.646 3.646 9.003 9.003 0 0012 21a9.003 9.003 0 008.354-5.646z"} />
                </svg>
                <span className="font-medium">{theme === 'dark' ? 'Light Mode' : 'Dark Mode'}</span>
              </button>
              <button
                onClick={() => setSidebarCollapsed(!sidebarCollapsed)}
                className="w-full flex items-center gap-3 px-3 py-2.5 rounded-xl text-slate-400 hover:text-white hover:bg-slate-800/50 transition-all"
              >
                <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                  <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d={sidebarCollapsed ? "M11 19l-7-7 7-7m8 14l-7-7 7-7" : "M13 19l7-7-7-7m-8 14l7-7-7-7"} />
                </svg>
                <span className="font-medium">{sidebarCollapsed ? 'Expand' : 'Collapse'}</span>
              </button>
            </div>
          )}
          {sidebarCollapsed && (
            <div className="flex flex-col gap-2">
              <button
                onClick={() => setTheme(theme === 'dark' ? 'light' : 'dark')}
                className="p-2.5 rounded-xl text-slate-400 hover:text-white hover:bg-slate-800/50 transition-all"
                title={theme === 'dark' ? 'Light Mode' : 'Dark Mode'}
              >
                <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                  <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d={theme === 'dark' ? "M12 3v1m0 16v1m9-9h-1M4 12H3m15.364 6.364l-.707-.707M6.343 6.343l-.707-.707m12.728 0l-.707.707M6.343 17.657l-.707.707M16 12a4 4 0 11-8 0 4 4 0 018 0z" : "M20.354 15.354A9 9 0 018.646 3.646 9.003 9.003 0 0012 21a9.003 9.003 0 008.354-5.646z"} />
                </svg>
              </button>
              <button
                onClick={() => setSidebarCollapsed(false)}
                className="p-2.5 rounded-xl text-slate-400 hover:text-white hover:bg-slate-800/50 transition-all"
                title="Expand Sidebar"
              >
                <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                  <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M13 19l7-7-7-7m-8 14l7-7-7-7" />
                </svg>
              </button>
            </div>
          )}
        </div>
      </div>
    </aside>
  );
}
