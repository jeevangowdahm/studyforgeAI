function GeminiProbe() {
  const [question, setQuestion] = useState('Give me a 6 mark answer structure for blockchain consensus.');
  const [answer, setAnswer] = useState('');
  const [status, setStatus] = useState<'idle' | 'loading' | 'error'>('idle');

  async function submit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    setStatus('loading');
    setAnswer('');

    try {
      const response = await fetch('/api/ai/chat', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ question }),
      });
      const data = await response.json();
      if (!response.ok) throw new Error(data.error || 'Gemini request failed');
      setAnswer(data.answer || data.answerText || 'Gemini returned an empty response.');
      setStatus('idle');
    } catch (error) {
      setStatus('error');
      setAnswer(error instanceof Error ? error.message : 'Gemini request failed');
    }
  }

  return (
    <section id="gemini" className="relative overflow-hidden px-5 py-28 md:py-36">
      <div className="photo-bg photo-bg-network" aria-hidden="true" />
      <div className="noise-layer" aria-hidden="true" />
      <div className="relative mx-auto grid max-w-7xl gap-16 lg:grid-cols-[0.9fr_1.1fr] lg:gap-20">
        <motion.div {...fadeUp()}>
          <div className="mb-8 flex items-center gap-4">
            <span className="text-[11px] font-semibold uppercase tracking-[0.4em] text-white/40">04</span>
            <span className="h-px w-16 bg-white/15" />
            <span className="text-[11px] font-semibold uppercase tracking-[0.4em] text-white/40">Live AI</span>
          </div>
          <h2 className="font-display text-4xl font-medium leading-[1.05] tracking-[-0.02em] text-white md:text-5xl">
            Try the engine <span className="italic text-white/50">right here.</span>
          </h2>
          <p className="mt-7 max-w-md text-base leading-8 text-white/55">
            This panel talks to our backend, which talks to Gemini. Your question never carries a key, and the answer is always generated live.
          </p>
          <div className="mt-10 divide-y divide-white/5 border-y border-white/5 text-sm">
            {['Gemini 1.5 Flash, server-side only', 'Zero client-side key exposure', 'Citation-ready responses'].map((item) => (
              <div key={item} className="flex items-center gap-4 py-4 text-white/60">
                <span className="h-1 w-1 rounded-full bg-[#8fd0ff]" />
                {item}
              </div>
            ))}
          </div>
        </motion.div>

        <motion.form
          onSubmit={submit}
          {...fadeUp(0.1)}
          className="rounded-3xl border border-white/10 bg-white/[0.03] p-8 shadow-[0_40px_80px_-40px_rgba(0,0,0,0.8)] backdrop-blur-xl md:p-10"
        >
          <label className="text-[11px] font-semibold uppercase tracking-[0.4em] text-white/40" htmlFor="gemini-question">
            Ask Gemini
          </label>
          <textarea
            id="gemini-question"
            value={question}
            onChange={(event) => setQuestion(event.target.value)}
            className="mt-5 min-h-40 w-full resize-none rounded-2xl border border-white/10 bg-black/30 p-5 text-base leading-7 text-white/90 outline-none transition placeholder:text-white/25 focus:border-[#8fd0ff]/40"
          />
          <button
            type="submit"
            disabled={status === 'loading'}
            className="mt-5 inline-flex w-full items-center justify-center gap-2 rounded-full bg-white px-8 py-4 text-sm font-semibold text-[#05070c] transition hover:bg-white/85 disabled:cursor-not-allowed disabled:opacity-50"
          >
            {status === 'loading' ? 'Generating…' : 'Generate answer'} <ArrowUpRight className="h-4 w-4" />
          </button>
          <div className="mt-6 min-h-48 whitespace-pre-wrap rounded-2xl border border-white/5 bg-black/30 p-6 text-[15px] leading-8 text-white/60">
            {answer || 'The response will appear here. Add a GEMINI_API_KEY to the environment to activate live generation.'}
          </div>
        </motion.form>
      </div>
    </section>
  );
}

